interface NotificationSeed {
  slug: string
  to: PersonId[]
  role: Role
  kind: NotificationKind
  title: string
  body?: string
  href: string
  ref?: EntityRef
  at: IsoDateTime
  read?: boolean
}

function notifications(seed: NotificationSeed): NotificationRecord[] {
  return seed.to.map((recipientId) => {
    const record: NotificationRecord = {
      id: `notification_${seed.slug}_${recipientId.slice('person_'.length)}`,
      recipientId,
      role: seed.role,
      kind: seed.kind,
      title: seed.title,
      href: seed.href,
      createdAt: seed.at,
    }
    if (seed.body) record.body = seed.body
    if (seed.ref) record.ref = seed.ref
    // Read a few minutes after it arrived.
    if (seed.read) record.readAt = new Date(Date.parse(seed.at) + 7 * 60_000).toISOString()
    return record
  })
}

